-- STATUS: DRAFT / NOT APPLIED.
-- Purpose: keep immutable coursework grades private until an authorized Teacher
-- explicitly publishes each grade version. Existing grade rows are not backfilled;
-- each remains unpublished until reviewed and released through the tenant API.
-- Depends on applied tenant foundation v2, Teacher account links, Coursework
-- submission grades (DRAFT_20261115_08), and College memberships.
-- This migration is intentionally non-idempotent. Apply only after migration-history
-- reconciliation, PostgreSQL rehearsal, backup, and separate migration approval.

BEGIN;

DO $preflight$
BEGIN
    IF to_regclass('public.coursework_submission_grades') IS NULL
       OR to_regclass('public.college_memberships') IS NULL THEN
        RAISE EXCEPTION 'Grade publication requires coursework_submission_grades and college_memberships';
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
         WHERE conrelid = 'public.coursework_submission_grades'::regclass
           AND conname = 'uq_coursework_grade_id_college'
           AND contype = 'u'
    ) OR NOT EXISTS (
        SELECT 1 FROM pg_constraint
         WHERE conrelid = 'public.college_memberships'::regclass
           AND conname = 'uq_college_memberships_id_user_college'
           AND contype = 'u'
    ) THEN
        RAISE EXCEPTION 'Grade publication composite foreign-key prerequisites are missing';
    END IF;

    IF EXISTS (
        SELECT 1
          FROM (VALUES
              ('coursework_submission_grades','id'),
              ('coursework_submission_grades','college_id'),
              ('college_memberships','id'),
              ('college_memberships','user_id'),
              ('college_memberships','college_id')
          ) AS required(table_name, column_name)
          JOIN pg_class relation ON relation.oid = to_regclass('public.' || required.table_name)
          LEFT JOIN pg_attribute attribute
            ON attribute.attrelid = relation.oid
           AND attribute.attname = required.column_name
           AND attribute.attnum > 0
           AND NOT attribute.attisdropped
          LEFT JOIN pg_type data_type ON data_type.oid = attribute.atttypid
         WHERE attribute.attnum IS NULL OR data_type.typname <> 'int4'
    ) THEN
        RAISE EXCEPTION 'Grade publication INTEGER key columns are missing or incompatible';
    END IF;
END;
$preflight$;

CREATE TABLE public.coursework_grade_publications (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    coursework_submission_grade_id INTEGER NOT NULL,
    college_id INTEGER NOT NULL,
    published_by_membership_id INTEGER NOT NULL,
    published_by_user_id INTEGER NOT NULL,
    published_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),

    CONSTRAINT uq_coursework_grade_publication_grade_college
        UNIQUE (coursework_submission_grade_id, college_id),
    CONSTRAINT uq_coursework_grade_publication_id_college
        UNIQUE (id, college_id),
    CONSTRAINT fk_coursework_grade_publication_grade_college
        FOREIGN KEY (coursework_submission_grade_id, college_id)
        REFERENCES public.coursework_submission_grades (id, college_id)
        ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_coursework_grade_publication_membership
        FOREIGN KEY (published_by_membership_id, published_by_user_id, college_id)
        REFERENCES public.college_memberships (id, user_id, college_id)
        ON DELETE RESTRICT ON UPDATE RESTRICT
);

CREATE INDEX ix_coursework_grade_publications_college_published_at
    ON public.coursework_grade_publications (college_id, published_at DESC);

CREATE FUNCTION public.attendx_reject_coursework_grade_publication_mutation()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $function$
BEGIN
    RAISE EXCEPTION 'Coursework grade publication history is append-only';
END;
$function$;

CREATE TRIGGER trg_coursework_grade_publications_no_update_delete
    BEFORE UPDATE OR DELETE ON public.coursework_grade_publications
    FOR EACH ROW
    EXECUTE FUNCTION public.attendx_reject_coursework_grade_publication_mutation();

CREATE TRIGGER trg_coursework_grade_publications_no_truncate
    BEFORE TRUNCATE ON public.coursework_grade_publications
    FOR EACH STATEMENT
    EXECUTE FUNCTION public.attendx_reject_coursework_grade_publication_mutation();

COMMIT;
