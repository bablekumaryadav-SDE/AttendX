    ON public.student_account_links (revoked_by_user_id, college_id);

CREATE FUNCTION public.attendx_guard_student_account_link()
RETURNS TRIGGER LANGUAGE plpgsql AS $function$
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'Student account-link history cannot be physically deleted';
    END IF;
    IF TG_OP = 'INSERT' THEN
        IF NEW.link_status <> 'active' THEN
            RAISE EXCEPTION 'A Student account link must be explicitly verified before activation';
        END IF;
        NEW.verified_at := clock_timestamp();
        NEW.created_at := NEW.verified_at;
        RETURN NEW;
    END IF;
    IF OLD.link_status <> 'active' OR NEW.link_status <> 'revoked' THEN
        RAISE EXCEPTION 'A Student account link can only transition once from active to revoked';
    END IF;
    IF NEW.id IS DISTINCT FROM OLD.id
       OR NEW.student_id IS DISTINCT FROM OLD.student_id
       OR NEW.user_id IS DISTINCT FROM OLD.user_id
       OR NEW.college_id IS DISTINCT FROM OLD.college_id
       OR NEW.verified_by_user_id IS DISTINCT FROM OLD.verified_by_user_id
       OR NEW.verified_at IS DISTINCT FROM OLD.verified_at
       OR NEW.created_at IS DISTINCT FROM OLD.created_at THEN
        RAISE EXCEPTION 'Verified Student account-link identity fields are immutable';
    END IF;
    NEW.revoked_at := clock_timestamp();
    RETURN NEW;
END;
$function$;

CREATE TRIGGER trg_student_account_link_history
    BEFORE INSERT OR UPDATE OR DELETE ON public.student_account_links
    FOR EACH ROW EXECUTE FUNCTION public.attendx_guard_student_account_link();

CREATE FUNCTION public.attendx_reject_student_account_link_truncate()
RETURNS TRIGGER LANGUAGE plpgsql AS $function$
BEGIN
    RAISE EXCEPTION 'Student account-link history cannot be truncated';
END;
$function$;

CREATE TRIGGER trg_student_account_link_no_truncate
    BEFORE TRUNCATE ON public.student_account_links
    FOR EACH STATEMENT EXECUTE FUNCTION public.attendx_reject_student_account_link_truncate();

COMMIT;
