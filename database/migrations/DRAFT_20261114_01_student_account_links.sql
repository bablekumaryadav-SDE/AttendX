CREATE TABLE public.student_account_links (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id INTEGER NOT NULL,
    user_id INTEGER NOT NULL,
    college_id INTEGER NOT NULL,
    link_status VARCHAR(12) NOT NULL DEFAULT 'active',
    verified_by_user_id INTEGER NOT NULL,
    verified_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    revoked_by_user_id INTEGER,
    revoked_at TIMESTAMPTZ,
    revocation_reason TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT uq_student_account_links_id_student_college UNIQUE (id, student_id, college_id),
    CONSTRAINT ck_student_account_links_status CHECK (link_status IN ('active', 'revoked')),
    CONSTRAINT ck_student_account_links_revocation CHECK (
        (link_status = 'active' AND revoked_by_user_id IS NULL AND revoked_at IS NULL AND revocation_reason IS NULL)
        OR (link_status = 'revoked' AND revoked_by_user_id IS NOT NULL AND revoked_at IS NOT NULL
            AND revocation_reason IS NOT NULL AND length(trim(revocation_reason)) > 0)
    ),
    CONSTRAINT fk_student_account_links_student_college FOREIGN KEY (student_id, college_id)
        REFERENCES public.students (id, college_id) ON DELETE RESTRICT,
    CONSTRAINT fk_student_account_links_user_college FOREIGN KEY (user_id, college_id)
        REFERENCES public.college_memberships (user_id, college_id) ON DELETE RESTRICT,
    CONSTRAINT fk_student_account_links_verifier_membership FOREIGN KEY (verified_by_user_id, college_id)
        REFERENCES public.college_memberships (user_id, college_id) ON DELETE RESTRICT,
    CONSTRAINT fk_student_account_links_revoker_membership FOREIGN KEY (revoked_by_user_id, college_id)
        REFERENCES public.college_memberships (user_id, college_id) ON DELETE RESTRICT
);

CREATE UNIQUE INDEX uq_student_account_links_active_student
    ON public.student_account_links (student_id) WHERE link_status = 'active';
CREATE UNIQUE INDEX uq_student_account_links_active_user_college
