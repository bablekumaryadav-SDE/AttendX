-- Grading is also recorded in the existing coursework assignment audit log.
ALTER TABLE public.coursework_assignment_audit_events
    DROP CONSTRAINT ck_coursework_audit_event_type;

ALTER TABLE public.coursework_assignment_audit_events
    ADD CONSTRAINT ck_coursework_audit_event_type
    CHECK (event_type IN ('published', 'deadline_extended', 'archived', 'graded'));


-- A revision must be addressable together with its owning submission and College.
ALTER TABLE public.coursework_submission_revisions
    ADD CONSTRAINT uq_coursework_revision_id_submission_college
    UNIQUE (id, coursework_submission_id, college_id);

CREATE TABLE public.coursework_submission_grades (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    coursework_submission_id INTEGER NOT NULL,
    revision_id INTEGER NOT NULL,
    college_id INTEGER NOT NULL,
    version INTEGER NOT NULL,
    marks_awarded NUMERIC(8,2) NOT NULL,
    feedback TEXT NULL,
    graded_by_membership_id INTEGER NOT NULL,
    graded_by_user_id INTEGER NOT NULL,
    graded_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),

    CONSTRAINT ck_coursework_grade_version CHECK (version >= 1),
    CONSTRAINT ck_coursework_grade_marks_nonnegative CHECK (marks_awarded >= 0),

    CONSTRAINT uq_coursework_grade_submission_revision_version
        UNIQUE (coursework_submission_id, revision_id, version),
    CONSTRAINT uq_coursework_grade_id_college
        UNIQUE (id, college_id),

    CONSTRAINT fk_coursework_grade_submission_college
        FOREIGN KEY (coursework_submission_id, college_id)
        REFERENCES public.coursework_submissions (id, college_id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_coursework_grade_revision_submission_college
        FOREIGN KEY (revision_id, coursework_submission_id, college_id)
        REFERENCES public.coursework_submission_revisions
            (id, coursework_submission_id, college_id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_coursework_grade_grader_membership
        FOREIGN KEY (graded_by_membership_id, graded_by_user_id, college_id)
        REFERENCES public.college_memberships (id, user_id, college_id)
        ON DELETE RESTRICT
);

CREATE INDEX ix_coursework_grade_submission_revision
    ON public.coursework_submission_grades
       (college_id, coursework_submission_id, revision_id, version DESC);

-- The assignment's configured maximum is enforced by the database too.
CREATE FUNCTION public.attendx_check_coursework_grade_marks()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $function$
DECLARE
    configured_maximum NUMERIC(8,2);
BEGIN
    SELECT assignment.maximum_marks
      INTO configured_maximum
      FROM public.coursework_submissions submission
      JOIN public.coursework_assignments assignment
        ON assignment.id = submission.coursework_assignment_id
       AND assignment.college_id = submission.college_id
     WHERE submission.id = NEW.coursework_submission_id
       AND submission.college_id = NEW.college_id;

    IF configured_maximum IS NOT NULL
       AND NEW.marks_awarded > configured_maximum THEN
        RAISE EXCEPTION 'Awarded marks exceed the assignment maximum';
    END IF;

    RETURN NEW;
END;
$function$;

CREATE TRIGGER trg_coursework_grade_marks_guard
    BEFORE INSERT ON public.coursework_submission_grades
    FOR EACH ROW
    EXECUTE FUNCTION public.attendx_check_coursework_grade_marks();

-- Grade history is append-only; corrections create a new version.
CREATE FUNCTION public.attendx_reject_coursework_grade_mutation()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $function$
BEGIN
    RAISE EXCEPTION 'Coursework grade history is append-only';
END;
$function$;

CREATE TRIGGER trg_coursework_grade_no_update_delete
    BEFORE UPDATE OR DELETE ON public.coursework_submission_grades
    FOR EACH ROW
    EXECUTE FUNCTION public.attendx_reject_coursework_grade_mutation();

CREATE FUNCTION public.attendx_reject_coursework_grade_truncate()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $function$
BEGIN
    RAISE EXCEPTION 'Coursework grade history cannot be truncated';
END;
$function$;

CREATE TRIGGER trg_coursework_grade_no_truncate
    BEFORE TRUNCATE ON public.coursework_submission_grades
    FOR EACH STATEMENT
    EXECUTE FUNCTION public.attendx_reject_coursework_grade_truncate();

COMMIT;
